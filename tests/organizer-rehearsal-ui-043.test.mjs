import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import {createRehearsalApi} from '../site/organizer-rehearsal.mjs';

test('053: empty organizer opens without fictional people, routes or events; a first real person can be added',async()=>{
 const html=readFileSync(new URL('../site/organisation.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://transbora-ludo.netlify.app/organisation.html',pretendToBeVisual:true});
 const w=dom.window;
 globalThis.window=w;globalThis.document=w.document;globalThis.location=w.location;
 globalThis.history=w.history;globalThis.FormData=w.FormData;
 globalThis.fetch=async()=>{throw Error('A local rehearsal must never request private organizer data');};
 await import('../site/organisation-app.mjs');
 await new Promise(resolve=>setTimeout(resolve,80));
 const $=id=>w.document.getElementById(id);
 assert.equal($('private-panel').hidden,false);
 assert.equal($('login-panel').hidden,true);
 assert.equal($('demo-warning').hidden,true);
 assert.equal($('company-name').hidden,true);
 assert.doesNotMatch(w.document.querySelector('.head').textContent,/organisation · aperçu/i);
 assert.doesNotMatch(w.document.querySelector('.masthead').textContent,/démonstration|tableau de bord/i);
 assert.match($('people-output').textContent,/Aucune personne enregistrée/);
 assert.match($('events-output').textContent,/Aucun événement enregistré/);
 assert.match($('month-register-body').textContent,/Aucun déplacement/);
 assert.equal((await createRehearsalApi(w.localStorage,{cleanExamples:true})('list',{type:'person'})).items.length,0);
 $('tabs').querySelector('[data-tab=people]').click();
 assert.equal($('person-editor').hidden,true);
 $('add-person-btn').click();
 assert.equal($('person-editor').hidden,false);
 const form=$('person-form');
 form.elements.name.value='Camille Martin';form.elements.departure.value='Brest';
 form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 await new Promise(resolve=>setTimeout(resolve,80));
 assert.equal($('person-editor').hidden,true);
 assert.match($('people-output').textContent,/Camille Martin/);
 assert.doesNotMatch($('people-output').textContent,/Sophie \(exemple\)/);
 assert.equal($('invite-form').hidden,true);
 w.close();
});
